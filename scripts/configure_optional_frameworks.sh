#!/bin/bash
# Writes Configuration/OptionalFrameworks.generated.xcconfig based on what
# optional binaries are present. Sourced by Debug/Release.xcconfig.
set -euo pipefail
ROOT="${SRCROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
OUT="${ROOT}/Configuration/OptionalFrameworks.generated.xcconfig"
FF="${ROOT}/vendor/frameworks/FFmpeg.framework"

{
  echo "// AUTO-GENERATED by scripts/configure_optional_frameworks.sh — do not edit."
  echo "// Regenerated on every xcodebuild via preBuildScripts."
  if [ -d "$FF" ]; then
    echo "// FFmpeg.framework detected — enabling native ffmpeg offload."
    echo 'OASES_HAVE_FFMPEG = 1'
    echo 'OTHER_CFLAGS = $(inherited) -DOASES_HAVE_FFMPEG=1'
    echo 'FRAMEWORK_SEARCH_PATHS = $(inherited) $(SRCROOT)/vendor/frameworks'
    echo 'OTHER_LDFLAGS = $(inherited) -framework FFmpeg'
    # Embed sibling lib*.framework if present next to the umbrella.
    for lib in avcodec avformat avutil avfilter swresample swscale; do
      if [ -d "${ROOT}/vendor/frameworks/lib${lib}.framework" ]; then
        echo "OTHER_LDFLAGS = \$(inherited) -framework lib${lib}"
      fi
    done
  else
    echo "// FFmpeg.framework not found at vendor/frameworks/ — offload stays a no-op."
    echo 'OASES_HAVE_FFMPEG = 0'
  fi
} > "$OUT"
echo "[optional-frameworks] wrote $OUT (ffmpeg=$([ -d "$FF" ] && echo yes || echo no))"
